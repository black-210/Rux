pub fn find_builtin(ns: &str, name: &str) -> Option<&'static BuiltinFnSpec> {
    BUILTIN_FNS.iter().find(|f| f.namespace == ns && f.name == name)
}

pub fn find_builtin_const(ns: &str, name: &str) -> Option<&'static BuiltinConstSpec> {
    BUILTIN_CONSTS.iter().find(|c| c.namespace == ns && c.name == name)
}

pub fn functions_in_namespace(ns: &str) -> Vec<&'static BuiltinFnSpec> {
    BUILTIN_FNS.iter().filter(|f| f.namespace == ns).collect()
}
